#!/usr/bin/env python3
"""Build the long version's YouTube upload text and verify its chapter times against the audio.

Inputs:  long/kit/Doing-and-Feeling-Long-manifest.json (chapter starts from Claude's assembly)
         long/kit/youtube/<episode>.youtube.txt     (TITLE / DESCRIPTION / TAGS / CHAPTERS)
         long/whisper/<episode>.json                        (our Whisper word timestamps)
Output:  long/youtube/<episode>.md, same layout as the short-series files (title, description with a CHAPTERS
         block before the 'Key sources:' paragraph, tags), so scripts/check.py can validate them.

Each chapter's opening words (manifest `first_words`) are located in the transcript near the
manifest time; the script reports the measured offset and fails if any chapter is off by more than
MAX_OFFSET seconds or cannot be found.
"""

import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KIT = ROOT / "long" / "kit"
TRANSCRIPTS = ROOT / "long" / "whisper"
OUT = ROOT / "long" / "youtube"
MAX_OFFSET = 1.5
SEARCH_WINDOW = 30


def norm(word):
    return re.sub(r"[^a-z0-9]", "", word.lower())


def sections(text):
    parts = re.split(r"^(TITLE|DESCRIPTION|TAGS|CHAPTERS):\s*$", text, flags=re.M)
    return {parts[i]: parts[i + 1].strip() for i in range(1, len(parts), 2)}


def transcript_words(name):
    data = json.loads((TRANSCRIPTS / f"{name}.json").read_text())
    words = []
    for segment in data["segments"]:
        for word in segment.get("words", []):
            for part in re.split(r"[-\s]+", word["word"]):
                if norm(part):
                    words.append((norm(part), word["start"]))
    return words


def locate(words, chapter):
    # Drop the last token: manifest first_words are cut at 60 characters mid-word.
    target = [norm(t) for t in chapter["first_words"].split()[:-1] if norm(t)][:8]
    best = None
    for i, (_, start) in enumerate(words):
        if abs(start - chapter["start"]) > SEARCH_WINDOW:
            continue
        candidate = [w for w, _ in words[i : i + len(target)]]
        score = difflib.SequenceMatcher(None, target, candidate).ratio()
        key = (score, -abs(start - chapter["start"]))
        if best is None or key > best[0]:
            best = (key, start)
    return best[1] - chapter["start"], best[0][0]


def main():
    manifest = json.loads((KIT / "Doing-and-Feeling-Long-manifest.json").read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    failures = []
    for episode in manifest["episodes"]:
        name = Path(episode["mp3"]).stem
        text = sections((KIT / "youtube" / f"{name}.youtube.txt").read_text())

        if (TRANSCRIPTS / f"{name}.json").exists():
            words = transcript_words(name)
            offsets = []
            for chapter in episode["chapters"][1:]:  # the first chapter is pinned to 0:00
                offset, score = locate(words, chapter)
                offsets.append(offset)
                if score < 0.3 or abs(offset) > MAX_OFFSET:  # spelled-out years and misheard names lower the score
                    failures.append(f"{name}: '{chapter['title']}' offset {offset:+.1f}s, match {score:.2f}")
            print(f"{name}: chapters verified, max offset {max(map(abs, offsets)):.1f}s")
        else:
            print(f"{name}: no transcript yet, chapters NOT verified")

        chapters = "\n".join(f"{c['timestamp']} {c['title']}" for c in episode["chapters"])
        intro, marker, rest = text["DESCRIPTION"].partition("\n\nKey sources:")
        if not marker:
            sys.exit(f"{name}: description has no 'Key sources:' paragraph to put the chapters before")
        description = f"{intro}\n\nCHAPTERS\n{chapters}{marker}{rest}".strip()
        (OUT / f"{name}.md").write_text(
            f"# Episode {episode['episode']} — {episode['short_title']}\n\n"
            f"- **File:** `long/out/videos/{name}.mp4`\n"
            f"- **Thumbnail:** `long/out/thumbnails/{name}.png`\n"
            f"- Generated by `scripts/long-youtube.py` from Claude's kit; edit the kit, not this file.\n\n"
            f"## Title\n\n```\n{text['TITLE']}\n```\n\n"
            f"## Description\n\n```\n{description}\n```\n\n"
            f"## Tags\n\n```\n{text['TAGS']}\n```\n"
        )

    if failures:
        print("\nCHAPTER CHECK FAILED:\n" + "\n".join(failures))
        sys.exit(1)


if __name__ == "__main__":
    main()
