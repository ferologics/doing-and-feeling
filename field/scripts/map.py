#!/usr/bin/env python3
"""Build the co-authorship map of the seed researchers.

Fetches every work since SINCE for each resolved author (cached in field/cache/), links two people when they
co-authored a work, and writes:
  field/map.md    summary: camps, strongest collaborations, cross-camp bridges, isolated people, per-person table
  field/map.html  interactive network (vis-network): colour = first camp, border = crux answer, width = joint works

Usage: field/scripts/map.py [--refresh]   (--refresh ignores the cached works)
"""

import collections
import html
import itertools
import json
import math
import sys

from openalex import FIELD, authors, people, short_id, works

SINCE = "2010-01-01"
CAMP_COLORS = {
    "global-workspace": "#e8b04b", "higher-order": "#d9822b", "recurrent-processing": "#c9a227", "iit": "#7fb2c9",
    "predictive-processing": "#6fcf97", "attention-schema": "#9b8cff", "illusionism": "#f28cb1", "self-model": "#e07aa8",
    "neurorepresentationalism": "#b0d47a", "biological-naturalism": "#e5534b", "panpsychism": "#a77bca",
    "idealism": "#8e6cc0", "orch-or": "#5f9ea0", "dualism": "#b3a1ff", "ual": "#7ccf8a", "evolution": "#4fb286",
    "basal-cognition": "#3fa37a", "metacognition": "#f0c27b", "methods": "#9aa0aa", "ai-consciousness": "#5ab0ff",
    "ai-welfare": "#ff9f6b", "computational-functionalism": "#4a8cff",
}
CRUX_BORDER = {"yes": "#4a8cff", "no": "#e5534b"}


def build(refresh):
    roster = {p["name"]: p for p in people()}
    resolved = authors()
    id_to_name = {a["openalex"]: name for name, a in resolved.items() if a.get("openalex")}
    edges = collections.defaultdict(list)  # (name, name) -> [(year, title)]
    counts = {}
    for name, author in resolved.items():
        if not author.get("openalex"):
            continue
        items = works(author["openalex"], SINCE, cache=not refresh, select="id,title,publication_year,authorships")
        counts[name] = len(items)
        for work in items:
            seeds = sorted({
                id_to_name[short_id(a["author"]["id"])]
                for a in work["authorships"]
                if a["author"].get("id") and short_id(a["author"]["id"]) in id_to_name
            })
            if not seeds or seeds[0] != name:
                continue  # count each work once: only when processing its alphabetically first seed author
            for pair in itertools.combinations(seeds, 2):
                edges[pair].append((work.get("publication_year") or 0, work.get("title") or ""))
    return roster, resolved, counts, edges


def write_markdown(roster, resolved, counts, edges):
    degree = collections.Counter()
    partners = collections.defaultdict(set)
    for (a, b), shared in edges.items():
        degree[a] += 1
        degree[b] += 1
        partners[a].add(b)
        partners[b].add(a)

    def camp(name):
        return (roster[name].get("camps") or ["unassigned"])[0]

    lines = [
        "# Field map: co-authorship among the seed researchers",
        "",
        f"Generated by `field/scripts/map.py` from OpenAlex (works since {SINCE[:4]}). Interactive version: `map.html`.",
        "Camps are first-pass tags from the series (see `people.toml`); two people are linked when they co-authored a work.",
        "",
        f"- {len(roster)} people, {len(counts)} with OpenAlex works, {sum(counts.values())} works in total",
        f"- {len(edges)} co-author links, {sum(len(v) for v in edges.values())} joint works",
        "",
        "## Strongest collaborations",
        "",
        "| Pair | Joint works | Latest |",
        "|---|---|---|",
    ]
    for (a, b), shared in sorted(edges.items(), key=lambda kv: -len(kv[1]))[:25]:
        year, title = max(shared)
        lines.append(f"| {a} — {b} | {len(shared)} | {year}: {html.escape(title[:80])} |")

    lines += ["", "## Bridges between camps", "", "People with the most co-authors outside their first camp.", ""]
    bridges = []
    for name in partners:
        outside = sorted(p for p in partners[name] if camp(p) != camp(name))
        if outside:
            bridges.append((len(outside), name, outside))
    for n, name, outside in sorted(bridges, reverse=True)[:15]:
        lines.append(f"- **{name}** ({camp(name)}): {', '.join(f'{p} ({camp(p)})' for p in outside)}")

    lines += ["", "## Camps", "", "| Camp | People | Links inside | Links to other camps |", "|---|---|---|---|"]
    members = collections.defaultdict(list)
    for name in roster:
        members[camp(name)].append(name)
    for c, names in sorted(members.items(), key=lambda kv: -len(kv[1])):
        inside = sum(1 for (a, b) in edges if camp(a) == c and camp(b) == c)
        outside = sum(1 for (a, b) in edges if (camp(a) == c) != (camp(b) == c))
        lines.append(f"| {c} | {len(names)} | {inside} | {outside} |")

    isolated = sorted(n for n in roster if not degree[n])
    lines += ["", "## No co-authors on the map", "", ", ".join(isolated) or "none", ""]

    lines += ["## People", "", "| Name | Camps | Crux | Works since 2010 | Co-authors on map | Institution (OpenAlex) |",
              "|---|---|---|---|---|---|"]
    for name, p in sorted(roster.items(), key=lambda kv: -degree[kv[0]]):
        a = resolved.get(name, {})
        crux = p.get("crux", "")
        lines.append(
            f"| {name} | {', '.join(p.get('camps') or [])} | {crux} | {counts.get(name, '–')} | {degree[name]} | "
            f"{a.get('institution') or ''} |"
        )
    (FIELD / "map.md").write_text("\n".join(lines) + "\n")
    return degree


def write_html(roster, resolved, counts, edges, degree):
    nodes = []
    for name, p in roster.items():
        camps = p.get("camps") or []
        a = resolved.get(name, {})
        tip = (f"{name}\ncamps: {', '.join(camps) or '–'}\ncrux: {p.get('crux', '–')}\n"
               f"works since 2010: {counts.get(name, '–')}\n{a.get('institution') or ''}")
        nodes.append({
            "id": name, "label": name, "title": tip, "value": 1 + degree[name],
            "color": {"background": CAMP_COLORS.get(camps[0] if camps else "", "#cccccc"),
                      "border": CRUX_BORDER.get(p.get("crux"), "#444444")},
            "borderWidth": 4 if p.get("crux") else 1,
        })
    links = []
    for (a, b), shared in edges.items():
        year, title = max(shared)
        links.append({"from": a, "to": b, "value": len(shared),
                      "title": f"{len(shared)} joint works\nlatest {year}: {title[:90]}", "width": 1 + math.log2(len(shared))})
    legend = "".join(
        f'<span style="background:{color}"></span>{camp}' for camp, color in CAMP_COLORS.items()
    )
    page = f"""<!doctype html>
<html><head><meta charset="utf-8"><title>Field map: consciousness research co-authorship</title>
<script src="https://unpkg.com/vis-network@9.1.9/standalone/umd/vis-network.min.js"></script>
<style>
  body {{ margin: 0; background: #111319; color: #f0eee8; font: 14px -apple-system, system-ui, sans-serif; }}
  #net {{ position: absolute; inset: 0; }}
  #legend {{ position: absolute; left: 12px; top: 12px; max-width: 360px; background: #1a1d24cc; padding: 10px 12px;
            border-radius: 8px; line-height: 1.8; }}
  #legend span {{ display: inline-block; width: 10px; height: 10px; border-radius: 50%; margin: 0 6px 0 10px; }}
  #legend b {{ display: block; margin-bottom: 4px; }}
</style></head><body>
<div id="net"></div>
<div id="legend"><b>Colour = first camp · thick blue/red border = computation enough? yes/no · edge = co-authored work</b>{legend}</div>
<script>
const nodes = new vis.DataSet({json.dumps(nodes)});
const edges = new vis.DataSet({json.dumps(links)});
new vis.Network(document.getElementById("net"), {{nodes, edges}}, {{
  nodes: {{ shape: "dot", scaling: {{ min: 8, max: 40 }}, font: {{ color: "#f0eee8", size: 14 }} }},
  edges: {{ color: {{ color: "#5b5f69", highlight: "#e8b04b" }}, smooth: false }},
  physics: {{ solver: "forceAtlas2Based", forceAtlas2Based: {{ gravitationalConstant: -60, springLength: 120 }},
             stabilization: {{ iterations: 400 }} }},
  interaction: {{ hover: true, tooltipDelay: 80 }}
}});
</script></body></html>
"""
    (FIELD / "map.html").write_text(page)


def main():
    roster, resolved, counts, edges = build(refresh="--refresh" in sys.argv)
    degree = write_markdown(roster, resolved, counts, edges)
    write_html(roster, resolved, counts, edges, degree)
    print(f"{len(edges)} co-author links among {len(roster)} people → field/map.md, field/map.html")


if __name__ == "__main__":
    main()
