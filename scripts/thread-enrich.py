#!/usr/bin/env python3
"""Enrich an X thread export with full post data from the public FxTwitter API.

Input:  notes/thread/x-thread-export.json (from scripts/x-thread-export.js)
Cache:  work/fx/<id>.json (one API response per post)
Output: notes/thread/posts.json (one record per post: author, text, expanded links, photos, quote,
        parent id, reply count), notes/thread/replies.md (readable, threaded), plus a printed
        report of sub-threads with missing replies.
"""

import json
import re
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPORT = ROOT / "notes" / "thread" / "x-thread-export.json"
CACHE = ROOT / "work" / "fx"
OUT = ROOT / "notes" / "thread" / "posts.json"
MARKDOWN = ROOT / "notes" / "thread" / "replies.md"


def fetch(post_id):
    cached = CACHE / f"{post_id}.json"
    if cached.exists():
        return json.loads(cached.read_text())
    request = urllib.request.Request(
        f"https://api.fxtwitter.com/status/{post_id}", headers={"User-Agent": "doing-and-feeling/1.0"}
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        data = json.loads(response.read())
    cached.write_text(json.dumps(data))
    time.sleep(0.5)
    return data


def record(post_id, data, exported):
    tweet = data.get("tweet")
    if not tweet:
        return {"id": post_id, "url": exported["url"], "error": data.get("message", "missing"), "export": exported}
    facets = (tweet.get("raw_text") or {}).get("facets") or []
    quote = tweet.get("quote")
    return {
        "id": post_id,
        "url": tweet["url"],
        "author": f"{tweet['author']['name']} (@{tweet['author']['screen_name']})",
        "created": tweet["created_at"],
        "parent": tweet.get("replying_to_status"),
        "replies": tweet.get("replies", 0),
        "likes": tweet.get("likes", 0),
        "text": re.sub(r"^(@\w+\s+)+", "", tweet.get("text", "")).strip(),
        "links": [f["replacement"] for f in facets if f.get("type") == "url" and f.get("replacement")],
        "photos": [p["url"] for p in (tweet.get("media") or {}).get("photos", [])],
        "videos": [v["url"] for v in (tweet.get("media") or {}).get("videos", [])],
        "card": exported.get("card") or "",
        "quote": quote and {
            "url": quote["url"],
            "author": quote["author"]["screen_name"],
            "text": quote.get("text", ""),
            "photos": [p["url"] for p in (quote.get("media") or {}).get("photos", [])],
        },
    }


def render(posts, children, root_id):
    lines = [
        "# Thread replies",
        "",
        "Generated by `scripts/thread-enrich.py` from `notes/thread/x-thread-export.json`. Do not edit by hand.",
        "Order is X's ranking order; nested replies follow their parent. ♥ = likes, ↩ = replies on X.",
        "",
    ]

    def emit(post, depth):
        if "error" in post:
            lines.append(f"{'  ' * depth}- **unavailable** {post['url']} ({post['error']})")
            return
        prefix = "  " * depth
        missing = post["replies"] - len(children.get(post["id"], []))
        meta = f"{post['likes']}♥ {post['replies']}↩" + (f", {missing} not captured" if missing > 0 else "")
        lines.append(f"{prefix}- **{post['author']}** ({meta}) [link]({post['url']})")
        for text_line in post["text"].splitlines():
            if text_line.strip():
                lines.append(f"{prefix}  > {text_line.strip()}")
        for link in post["links"]:
            lines.append(f"{prefix}  - link: {link}")
        if post["card"]:
            lines.append(f"{prefix}  - card: {post['card']}")
        if post["quote"]:
            quote_text = post["quote"]["text"].replace("\n", " ")[:400]
            lines.append(f"{prefix}  - quotes @{post['quote']['author']}: {quote_text} ({post['quote']['url']})")
        for photo in post["photos"]:
            lines.append(f"{prefix}  - photo: {photo}")
        for child_id in children.get(post["id"], []):
            emit(by_id[child_id], depth + 1)

    by_id = {p["id"]: p for p in posts}
    emit(by_id[root_id], 0)
    MARKDOWN.write_text("\n".join(lines) + "\n")


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    exported = json.loads(EXPORT.read_text())
    posts = []
    for item in exported:
        post_id = item["url"].rstrip("/").split("/")[-1]
        posts.append(record(post_id, fetch(post_id), item))
    OUT.write_text(json.dumps(posts, indent=2, ensure_ascii=False))

    by_id = {p["id"]: p for p in posts}
    children = {}
    for p in posts:
        children.setdefault(p.get("parent"), []).append(p["id"])
    root_id = next(p["id"] for p in posts if p.get("parent") not in by_id)
    render(posts, children, root_id)

    print(f"{len(posts)} posts, {sum('error' in p for p in posts)} API errors")
    print("sub-threads with fewer captured replies than their reply count:")
    for p in posts:
        if "error" in p:
            continue
        got = len(children.get(p["id"], []))
        if p["replies"] > got:
            print(f"  {p['replies'] - got:3d} missing  ({got}/{p['replies']})  {p['url']}")
    orphans = [p for p in posts if p.get("parent") and p["parent"] not in by_id]
    print(f"posts whose parent was not captured: {len(orphans)}")


if __name__ == "__main__":
    main()
